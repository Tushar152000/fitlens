export const EXERCISE_BY_SLUG = new Map(EXERCISES.map((e) => [e.slug, e]));

const normal = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z ]/g, " ")
    .replace(/\s+/g, " ")
    .trim();

/** True if any injury the user listed ("left knee pain") matches the exercise's avoid list ("knee"). */
export function ruledOutByInjury(exercise: ExerciseDef, injuries: string[]): boolean {
  const hurt = injuries.map(normal).filter(Boolean);
  return exercise.avoidIf.some((a) => hurt.some((h) => h.includes(normal(a))));
}

/** Options for a slot the user can do with their equipment and injuries, best first. */
export function optionsFor(slot: Slot, equipment: Equipment, injuries: string[]): ExerciseDef[] {
  return EXERCISES.filter(
    (e) => e.slot === slot && e.equipment.includes(equipment) && !ruledOutByInjury(e, injuries),
  );
}
